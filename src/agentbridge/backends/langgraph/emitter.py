"""IR -> a runnable LangGraph program.

Emits a small Python package rather than one file, so each concern lands
somewhere a human can read and edit: state shape, tool wiring, skill lowering,
agent construction, graph assembly.

Two decisions worth knowing before editing this module:

* Skills become tools whose return value is the skill body. This is the
  canonical lowering; the reasoning (and the rejected alternatives) live in
  `agentbridge.mapping.concepts`.
* `build_graph()` takes an injectable `model_factory`. That is not a testing
  afterthought — it is what lets the conformance suite build the real graph
  without an API key, and it is also the seam a deployment target uses to swap
  in a different provider.
"""

from __future__ import annotations

from agentbridge.backends.base import EmittedFile, RuntimeBackend
from agentbridge.diagnostics import DiagnosticBag
from agentbridge.ir.models import (
    END,
    Agent,
    Bundle,
    EngineContract,
    FieldType,
    Reducer,
    Skill,
    WorkflowMode,
)

PACKAGE = "workflow"
GENERATED_HEADER = '"""Generated by agentbridge. Edit the spec, not this file."""'


class LangGraphBackend(RuntimeBackend):
    name = "langgraph"
    description = "A runnable LangGraph program (StateGraph, nodes, conditional edges)."

    def emit(self, bundle: Bundle, diagnostics: DiagnosticBag) -> list[EmittedFile]:
        if bundle.workflow.mode is WorkflowMode.AUTONOMOUS:
            self._warn_autonomous(bundle, diagnostics)

        files = [
            EmittedFile(path=f"{PACKAGE}/__init__.py", content=_init_py(bundle)),
            EmittedFile(path=f"{PACKAGE}/state.py", content=_state_py(bundle)),
            EmittedFile(path=f"{PACKAGE}/skills.py", content=_skills_py(bundle, diagnostics)),
            EmittedFile(path=f"{PACKAGE}/tools.py", content=_tools_py(bundle, diagnostics)),
            EmittedFile(path=f"{PACKAGE}/agents.py", content=_agents_py(bundle)),
            EmittedFile(path=f"{PACKAGE}/graph.py", content=_graph_py(bundle)),
            EmittedFile(path="requirements.txt", content=_requirements()),
            EmittedFile(path="README.md", content=_readme(bundle)),
        ]
        return files

    def contract(self, bundle: Bundle, files: list[EmittedFile]) -> EngineContract:
        by_path = {str(f.path): f.content for f in files}
        agents_src = by_path.get(f"{PACKAGE}/agents.py", "")
        tools_src = by_path.get(f"{PACKAGE}/tools.py", "")
        skills_src = by_path.get(f"{PACKAGE}/skills.py", "")
        graph_src = by_path.get(f"{PACKAGE}/graph.py", "")

        agents = {a.name for a in bundle.ordered_agents() if _node_fn(a.name) in agents_src}
        tools = {t.name for t in bundle.ordered_tools() if _tool_var(t.name) in tools_src}
        skills = {s.name for s in bundle.ordered_skills() if _skill_var(s.name) in skills_src}
        nodes = {n.name for n in bundle.workflow.nodes if f'"{n.name}"' in graph_src}
        entry = bundle.workflow.entry
        if bundle.workflow.mode is WorkflowMode.AUTONOMOUS:
            # The flattened single node stands in for the whole workflow, and
            # the contract must say so rather than claim the declared nodes.
            nodes = {_autonomous_node(bundle)} if bundle.agents else set()
            entry = next(iter(sorted(nodes)), None)
        return EngineContract(
            engine=self.name,
            agents=frozenset(agents),
            skills=frozenset(skills),
            tools=frozenset(tools),
            nodes=frozenset(nodes),
            entry=entry,
        )

    def _warn_autonomous(self, bundle: Bundle, diagnostics: DiagnosticBag) -> None:
        extra = sorted(set(bundle.agents) - {_autonomous_node(bundle)}) if bundle.agents else []
        diagnostics.warn(
            "BRIDGE200",
            f"workflow {bundle.workflow.name!r} declares no graph, so it compiles "
            f"to a single node running {_autonomous_node(bundle)!r}"
            + (f"; {len(extra)} other agent(s) are unreachable: {extra}" if extra else ""),
            location=bundle.workflow.location,
            hint="add a graph: section to workflow.yaml to keep multi-agent structure",
        )


# --------------------------------------------------------------------------
# naming
# --------------------------------------------------------------------------


def _ident(name: str) -> str:
    out = "".join(c if c.isalnum() else "_" for c in name)
    return f"_{out}" if out and out[0].isdigit() else out


def _node_fn(agent_name: str) -> str:
    return f"make_{_ident(agent_name)}_node"


def _tool_var(tool_name: str) -> str:
    return f"tool_{_ident(tool_name)}"


def _skill_var(skill_name: str) -> str:
    return f"skill_{_ident(skill_name)}"


def _autonomous_node(bundle: Bundle) -> str:
    """The single agent an autonomous workflow collapses onto."""
    return sorted(bundle.agents)[0] if bundle.agents else "agent"


def _literal(value: str) -> str:
    """A readable Python string literal — generated code gets read."""
    if '"""' not in value and "\\" not in value and not value.endswith('"'):
        return f'"""{value}"""'
    return repr(value)



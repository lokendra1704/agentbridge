def _init_py(bundle: Bundle) -> str:
    return "\n".join(
        [
            f'"""{bundle.workflow.name}: generated by agentbridge."""',
            "",
            f"from {PACKAGE}.graph import build_graph",
            "",
            '__all__ = ["build_graph"]',
            "",
        ]
    )


def _requirements() -> str:
    return "\n".join(
        [
            "langgraph>=0.3.0",
            "langchain-core>=0.3.0",
            "langchain-anthropic>=0.3.0",
            "",
            "# LangGraph 1.0 moved the prebuilt agent to langchain.agents.create_agent.",
            "# workflow/agents.py works with or without this; installing it takes the",
            "# current path instead of the deprecated langgraph.prebuilt one.",
            "langchain>=1.0",
            "",
            "# The bridge's builtin tool shims (read/write/bash/glob/grep). Only",
            "# needed if the spec declares a tool with `builtin:`.",
            "agentbridge",
            "",
        ]
    )


def _readme(bundle: Bundle) -> str:
    wf = bundle.workflow
    autonomous = wf.mode is WorkflowMode.AUTONOMOUS
    lines = [
        f"# {wf.name} (LangGraph)",
        "",
        wf.description,
        "",
        "Generated by agentbridge. Edit the spec, not these files.",
        "",
        "## Run it",
        "",
        "```bash",
        "pip install -r requirements.txt",
        "export ANTHROPIC_API_KEY=...",
        'python -c "from workflow import build_graph; '
        "print(build_graph().invoke({'messages': [('user', 'hello')]}))\"",
        "```",
        "",
        "## Layout",
        "",
        "| File | What it holds |",
        "|---|---|",
        f"| `{PACKAGE}/state.py` | The typed state and its reducers |",
        f"| `{PACKAGE}/tools.py` | Tool wiring |",
        f"| `{PACKAGE}/skills.py` | Skills, lowered to load-on-demand tools |",
        f"| `{PACKAGE}/agents.py` | One node factory per agent |",
        f"| `{PACKAGE}/graph.py` | Graph assembly and `build_graph()` |",
        "",
        "## Swapping the model",
        "",
        "`build_graph(model_factory=...)` replaces `default_model_factory`. Use it",
        "to change provider, route agents to different models, or stub the model",
        "in tests.",
        "",
    ]
    if autonomous:
        lines += [
            "## Note on structure",
            "",
            "This spec declared no graph, so the program is a single node running",
            f"the `{_autonomous_node(bundle)}` agent. Add a `graph:` section to",
            "`workflow.yaml` to keep multi-agent structure on this engine.",
            "",
        ]
    return "\n".join(lines)

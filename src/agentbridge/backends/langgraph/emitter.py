def _state_py(bundle: Bundle) -> str:
    schema = bundle.workflow.state
    lines = [
        GENERATED_HEADER,
        "",
        "from __future__ import annotations",
        "",
        "import operator",
        "from typing import Annotated, Any, TypedDict",
        "",
    ]

    has_messages = schema.transcript_field is not None
    has_merge = any(f.reducer is Reducer.MERGE for f in schema.fields)
    if has_messages:
        lines += [
            "from langchain_core.messages import AnyMessage",
            "from langgraph.graph.message import add_messages",
            "",
        ]
    if has_merge:
        lines += [
            "",
            "def merge_dicts(left: dict[str, Any], right: dict[str, Any]) -> dict[str, Any]:",
            '    """Reducer for `merge` fields: right-hand keys win."""',
            "    return {**left, **right}",
            "",
        ]

    lines += ["", f"class {schema.name}(TypedDict, total=False):"]
    if not schema.fields:
        lines.append('    """No state fields were declared in the spec."""')
        lines.append("")
        return "\n".join(lines) + "\n"

    doc = ['    """State carried between nodes.', ""]
    for field in schema.fields:
        doc.append(f"    {field.name}: {field.description or field.type.value}")
    doc += ['    """', ""]
    lines += doc

    for field in schema.fields:
        lines.append(f"    {field.name}: {_annotation(field)}")
    lines.append("")
    return "\n".join(lines) + "\n"


_BASE_TYPES = {
    FieldType.STR: "str",
    FieldType.INT: "int",
    FieldType.FLOAT: "float",
    FieldType.BOOL: "bool",
    FieldType.LIST: "list[Any]",
    FieldType.DICT: "dict[str, Any]",
    FieldType.MESSAGES: "list[AnyMessage]",
}


def _annotation(field: object) -> str:
    ftype: FieldType = field.type  # type: ignore[attr-defined]
    reducer: Reducer = field.reducer  # type: ignore[attr-defined]
    base = _BASE_TYPES[ftype]
    if ftype is FieldType.MESSAGES:
        return f"Annotated[{base}, add_messages]"
    if reducer is Reducer.APPEND:
        return f"Annotated[{base}, operator.add]"
    if reducer is Reducer.MERGE:
        return f"Annotated[{base}, merge_dicts]"
    return base


# --------------------------------------------------------------------------
# skills.py — the canonical skill lowering
# --------------------------------------------------------------------------


def _skills_py(bundle: Bundle, diagnostics: DiagnosticBag) -> str:
    lines = [
        '"""Skills, lowered to tools. Generated by agentbridge.',
        "",
        "LangGraph has no lazy, model-triggered instruction primitive. Each skill",
        "becomes a zero-argument tool whose return value is the skill body, so the",
        "model still decides when to pull the instructions into context and pays",
        "no token cost until it does. The skill description becomes the tool",
        "description, which is what the model routes on.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from langchain_core.tools import StructuredTool",
        "",
    ]

    if not bundle.skills:
        lines += ["", "SKILL_TOOLS: dict[str, StructuredTool] = {}", ""]
        return "\n".join(lines) + "\n"

    for skill in bundle.ordered_skills():
        diagnostics.info(
            "BRIDGE202",
            f"skill {skill.name!r} is lowered to a tool that returns its body",
            location=skill.location,
        )
        const = f"{_ident(skill.name).upper()}_BODY"
        fn = f"_load_{_ident(skill.name)}"
        lines += [
            "",
            f"{const} = {_literal(_skill_body(skill))}",
            "",
            "",
            f"def {fn}() -> str:",
            f"    {_literal(_skill_tool_description(skill))}",
            f"    return {const}",
            "",
            "",
            f"{_skill_var(skill.name)} = StructuredTool.from_function(",
            f"    func={fn},",
            f'    name="skill_{_ident(skill.name)}",',
            f"    description={_literal(_skill_tool_description(skill))},",
            ")",
        ]

    lines += [
        "",
        "",
        "SKILL_TOOLS: dict[str, StructuredTool] = {",
    ]
    for skill in bundle.ordered_skills():
        lines.append(f'    "{skill.name}": {_skill_var(skill.name)},')
    lines += ["}", ""]
    return "\n".join(lines) + "\n"


def _skill_body(skill: Skill) -> str:
    body = skill.body.strip() or f"(The {skill.name} skill has no body.)"
    if skill.resources:
        listed = "\n".join(f"- {r}" for r in skill.resources)
        body += f"\n\n## Bundled resources\n\n{listed}"
    return body


def _skill_tool_description(skill: Skill) -> str:
    return (
        f"{skill.description.strip()} "
        "Call this to load the full instructions before you act on them."
    )



# tools.py
# --------------------------------------------------------------------------


def _tools_py(bundle: Bundle, diagnostics: DiagnosticBag) -> str:
    lines = [
        GENERATED_HEADER,
        "",
        "from __future__ import annotations",
        "",
        "from langchain_core.tools import StructuredTool",
        "",
    ]

    imports: list[str] = []
    bodies: list[str] = []

    for tool in bundle.ordered_tools():
        alias = f"_impl_{_ident(tool.name)}"
        if tool.implementation:
            module, _, attr = tool.implementation.partition(":")
            imports.append(f"from {module} import {attr} as {alias}")
        else:
            builtin = tool.builtin or ""
            shim = _BUILTIN_SHIMS.get(builtin)
            if shim is None:
                diagnostics.warn(
                    "BRIDGE201",
                    f"builtin tool {builtin!r} has no LangGraph equivalent; a stub "
                    "that raises NotImplementedError is emitted in its place",
                    location=tool.location,
                    hint=(
                        "supply an 'implementation:' for it, or use one of: "
                        f"{sorted(_BUILTIN_SHIMS)}"
                    ),
                )
                bodies += [
                    "",
                    "",
                    f"def {alias}(*args: object, **kwargs: object) -> str:",
                    f'    """Stub for builtin {builtin!r}, which this engine does not provide."""',
                    "    raise NotImplementedError(",
                    f'        "tool {tool.name!r} maps to engine builtin {builtin!r}, which "',
                    '        "LangGraph does not provide; supply an implementation in the spec"',
                    "    )",
                ]
            else:
                diagnostics.info(
                    "BRIDGE201",
                    f"builtin tool {builtin!r} is served by the agentbridge runtime shim "
                    f"{shim!r}, which is deliberately simpler than the native tool",
                    location=tool.location,
                )
                imports.append(f"from agentbridge.runtime.builtins import {shim} as {alias}")

    lines += sorted(set(imports))
    lines += bodies
    lines += ["", ""]

    for tool in bundle.ordered_tools():
        alias = f"_impl_{_ident(tool.name)}"
        if tool.parameters:
            lines.append(f"# declared parameter schema: {tool.parameters}")
            lines.append("# (inferred here from the callable's signature, which is authoritative)")
        lines += [
            f"{_tool_var(tool.name)} = StructuredTool.from_function(",
            f"    func={alias},",
            f'    name="{tool.name}",',
            f"    description={_literal(tool.description.strip())},",
            ")",
            "",
        ]

    lines += ["", "TOOLS: dict[str, StructuredTool] = {"]
    for tool in bundle.ordered_tools():
        lines.append(f'    "{tool.name}": {_tool_var(tool.name)},')
    lines += ["}", ""]
    return "\n".join(lines) + "\n"


#: Engine builtins the bridge can serve itself, so a spec that uses them
#: actually runs on both engines rather than merely compiling.
_BUILTIN_SHIMS = {
    "Read": "read_file",
    "Write": "write_file",
    "Edit": "edit_file",
    "Bash": "run_bash",
    "Glob": "glob_files",
    "Grep": "grep_files",
}



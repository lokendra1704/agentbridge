def _graph_py(bundle: Bundle) -> str:
    wf = bundle.workflow
    state = wf.state.name
    lines = [
        GENERATED_HEADER,
        "",
        "from __future__ import annotations",
        "",
        "from typing import Any",
        "",
        "from langgraph.graph import END, StateGraph",
        "",
        f"from {PACKAGE} import agents as _agents",
        f"from {PACKAGE}.agents import ModelFactory",
        f"from {PACKAGE}.state import {state}",
        "",
    ]

    if wf.mode is WorkflowMode.GRAPH:
        for branch in wf.branches:
            module, _, attr = branch.condition.partition(":")
            lines.append(f"from {module} import {attr} as _route_{_ident(branch.source)}")
        if wf.branches:
            lines.append("")
        for node in wf.nodes:
            if node.function:
                module, _, attr = node.function.partition(":")
                lines.append(f"from {module} import {attr} as _fn_{_ident(node.name)}")
        lines.append("")

    lines += [
        "",
        "def build_graph(",
        "    config: Any = None,",
        "    *,",
        "    checkpointer: Any = None,",
        "    model_factory: ModelFactory | None = None,",
        ") -> Any:",
        f'    """Assemble the {wf.name!r} workflow.',
        "",
        f"    {wf.description}",
        "",
        "    `config` is accepted and ignored so this doubles as a LangGraph",
        "    Platform graph factory. Leave `checkpointer` unset when deployed —",
        "    the platform supplies its own.",
        '    """',
        f"    builder = StateGraph({state})",
    ]

    if wf.mode is WorkflowMode.GRAPH:
        lines += _graph_body(bundle)
    else:
        lines += _autonomous_body(bundle)

    lines += [
        "    return builder.compile(checkpointer=checkpointer)",
        "",
        "",
        '__all__ = ["build_graph"]',
    ]
    return "\n".join(lines) + "\n"


def _graph_body(bundle: Bundle) -> list[str]:
    wf = bundle.workflow
    out: list[str] = []
    for node in wf.nodes:
        if node.agent:
            factory = f"_agents.{_node_fn(node.agent)}(model_factory)"
        else:
            factory = f"_fn_{_ident(node.name)}"
        out.append(f'    builder.add_node("{node.name}", {factory})')

    out.append("")
    out.append(f'    builder.set_entry_point("{wf.entry}")')
    for edge in wf.edges:
        target = "END" if edge.target == END else f'"{edge.target}"'
        out.append(f'    builder.add_edge("{edge.source}", {target})')

    for branch in wf.branches:
        mapping = ", ".join(
            f'"{label}": ' + ("END" if target == END else f'"{target}"')
            for label, target in sorted(branch.targets.items())
        )
        out += [
            "",
            f"    # {branch.description}",
            "    builder.add_conditional_edges(",
            f'        "{branch.source}",',
            f"        _route_{_ident(branch.source)},",
            "        {" + mapping + "},",
            "    )",
        ]
    out.append("")
    return out


def _autonomous_body(bundle: Bundle) -> list[str]:
    """One node, because a spec with no declared structure has no graph.

    Documented in the generated file too — someone reading the output should
    not have to guess why their four agents became one node.
    """
    agent = _autonomous_node(bundle)
    return [
        "    # The spec declared no graph, so there is no structure to build.",
        "    # This is a single node running one agent's own tool-calling loop.",
        "    # Add a graph: section to workflow.yaml to keep multi-agent structure.",
        f'    builder.add_node("{agent}", _agents.{_node_fn(agent)}(model_factory))',
        f'    builder.set_entry_point("{agent}")',
        f'    builder.add_edge("{agent}", END)',
        "",
    ]



def _agents_py(bundle: Bundle) -> str:
    lines = [
        GENERATED_HEADER,
        "",
        "from __future__ import annotations",
        "",
        "from collections.abc import Callable",
        "from typing import Any",
        "",
        "from langchain_core.language_models import BaseChatModel",
        "",
        f"from {PACKAGE}.skills import SKILL_TOOLS",
        f"from {PACKAGE}.state import {bundle.workflow.state.name}",
        f"from {PACKAGE}.tools import TOOLS",
        "",
        "",
        "def _build_agent(model: BaseChatModel, tools: list[Any], prompt: str) -> Any:",
        '    """Build a tool-calling agent across the two prebuilt-agent APIs.',
        "",
        "    LangGraph 1.0 moved this into langchain and renamed the prompt",
        "    keyword, so the import path alone is not enough to tell them apart.",
        '    """',
        "    try:",
        "        from langchain.agents import create_agent",
        "    except ImportError:  # langgraph < 1.0",
        "        from langgraph.prebuilt import create_react_agent",
        "",
        "        return create_react_agent(model, tools=tools, prompt=prompt)",
        "    return create_agent(model, tools=tools, system_prompt=prompt)",
        "",
        "",
        "ModelFactory = Callable[..., BaseChatModel]",
        "",
        "",
        "def default_model_factory(",
        "    name: str,",
        "    *,",
        "    max_tokens: int | None = None,",
        "    effort: str | None = None,",
        "    temperature: float | None = None,",
        ") -> BaseChatModel:",
        '    """Build the chat model for an agent.',
        "",
        "    Swap this out via build_graph(model_factory=...) to change provider,",
        "    to stub the model in tests, or to route different agents elsewhere.",
        '    """',
        "    from langchain_anthropic import ChatAnthropic",
        "",
        '    kwargs: dict[str, Any] = {"model": name}',
        "    if max_tokens is not None:",
        '        kwargs["max_tokens"] = max_tokens',
        "    if temperature is not None:",
        '        kwargs["temperature"] = temperature',
        "    if effort is not None:",
        "        # Reasoning depth rides in the request body, not as a client kwarg.",
        '        kwargs["model_kwargs"] = {"output_config": {"effort": effort}}',
        "    return ChatAnthropic(**kwargs)",
        "",
    ]

    for agent in bundle.ordered_agents():
        lines += _agent_node(bundle, agent)

    return "\n".join(lines) + "\n"


def _agent_node(bundle: Bundle, agent: Agent) -> list[str]:
    model = agent.model or bundle.workflow.model
    tool_refs = [f'TOOLS["{t.name}"]' for t in bundle.agent_tools(agent)]
    tool_refs += [f'SKILL_TOOLS["{s.name}"]' for s in bundle.agent_skills(agent)]
    tools_expr = "[" + ", ".join(tool_refs) + "]" if tool_refs else "[]"

    prompt_const = f"{_ident(agent.name).upper()}_PROMPT"
    state = bundle.workflow.state.name
    transcript = bundle.workflow.state.transcript_field
    field = transcript.name if transcript else "messages"

    model_args = [f'"{model.name}"']
    if model.max_tokens is not None:
        model_args.append(f"max_tokens={model.max_tokens}")
    if model.effort is not None:
        model_args.append(f'effort="{model.effort.value}"')
    if model.temperature is not None:
        model_args.append(f"temperature={model.temperature}")

    return [
        "",
        f"{prompt_const} = {_literal(agent.prompt.strip() or agent.description)}",
        "",
        "",
        f"def {_node_fn(agent.name)}(",
        "    model_factory: ModelFactory | None = None,",
        f") -> Callable[[{state}], dict[str, Any]]:",
        f'    """Build the node for the {agent.name!r} agent.',
        "",
        f"    {agent.description}",
        '    """',
        "    factory = model_factory or default_model_factory",
        f"    model = factory({', '.join(model_args)})",
        f"    agent = _build_agent(model, {tools_expr}, {prompt_const})",
        "",
        f"    def node(state: {state}) -> dict[str, Any]:",
        f'        history = list(state.get("{field}", []))',
        '        result = agent.invoke({"messages": history})',
        "        # Return only what this turn added; the reducer merges it in.",
        f'        return {{"{field}": result["messages"][len(history):]}}',
        "",
        f'    node.__name__ = "{_ident(agent.name)}"',
        "    return node",
        "",
    ]


